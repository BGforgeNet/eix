//! The reference pages: `docs/scripting.md` is generated from `docs/scripting.yml`, `docs/lua-reference.md` from
//! `docs/eix.lua`. The data files are the one home of every signature and description; `cargo xtask docs` writes the
//! pages and `cargo xtask check` fails when a page is stale.
//!
//! The data files are embedded, so tests of the Windows crates (which run under Wine) read the same text.

#![warn(missing_docs, unreachable_pub)]

#[cfg(test)]
mod gameexe;
pub mod luaapi;
pub mod scripting;

use std::fmt;

/// The script functions and commands, as the data file holds them.
pub const SCRIPTING_DATA: &str = include_str!("../../../docs/scripting.yml");

/// The Lua definitions file.
pub const LUA_DEFINITIONS: &str = include_str!("../../../docs/eix.lua");

/// Why a data file could not be turned into a page.
#[derive(Debug, PartialEq, Eq)]
pub struct DocsError(String);

impl DocsError {
    pub(crate) fn new(message: impl Into<String>) -> Self {
        Self(message.into())
    }
}

impl fmt::Display for DocsError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for DocsError {}

/// A generated page: its path under `docs/` and its text.
#[derive(Debug)]
pub struct Page {
    /// The file name under `docs/`.
    pub file: &'static str,
    /// The page's text.
    pub text: String,
}

/// Both pages, generated from the embedded data files.
pub fn pages() -> Result<[Page; 2], DocsError> {
    pages_from(SCRIPTING_DATA, LUA_DEFINITIONS)
}

fn pages_from(scripting: &str, lua: &str) -> Result<[Page; 2], DocsError> {
    Ok([
        Page {
            file: "scripting.md",
            text: scripting::Scripting::parse(scripting)?.render(),
        },
        Page {
            file: "lua-reference.md",
            text: luaapi::LuaApi::parse(lua)?.render(),
        },
    ])
}

/// The note at the top of a generated page.
const GENERATED: &str = "<!-- Generated by `cargo xtask docs` from";

/// The line that opens a generated page, naming its data file.
pub(crate) fn generated_note(data_file: &str) -> String {
    format!("{GENERATED} {data_file}; edit that file, not this page. -->")
}

/// The width the pages' prose is wrapped at.
const WIDTH: usize = 120;

/// Appends a paragraph wrapped at [`WIDTH`]. A line never starts with a character that Markdown reads as a list,
/// heading or quote, so a word that would is kept on the line before.
pub(crate) fn push_wrapped(out: &mut String, text: &str) {
    let mut line = String::new();
    for word in text.split_whitespace() {
        let starts_block = matches!(word, "-" | "+" | "*" | ">")
            || word.bytes().all(|b| b == b'#')
            || word
                .strip_suffix('.')
                .is_some_and(|d| !d.is_empty() && d.bytes().all(|b| b.is_ascii_digit()));
        if !line.is_empty() && line.len() + 1 + word.len() > WIDTH && !starts_block {
            out.push_str(&line);
            out.push('\n');
            line.clear();
        }
        if !line.is_empty() {
            line.push(' ');
        }
        line.push_str(word);
    }
    out.push_str(&line);
    out.push('\n');
}

/// A heading's anchor as mdBook derives it: lowercase letters and digits, `_` and `-` kept, whitespace to `-`.
pub fn anchor(heading: &str) -> String {
    heading
        .chars()
        .filter_map(|c| match c {
            c if c.is_alphanumeric() || c == '_' || c == '-' => Some(c.to_ascii_lowercase()),
            c if c.is_whitespace() => Some('-'),
            _ => None,
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn anchors_follow_mdbook() {
        assert_eq!(
            anchor("Players, parties and diplomacy"),
            "players-parties-and-diplomacy"
        );
        assert_eq!(anchor("Types"), "types");
    }

    #[test]
    fn a_wrapped_line_never_starts_a_block() {
        let mut out = String::new();
        let filler = "word ".repeat(23);
        push_wrapped(&mut out, &format!("{filler}- 1. # end"));
        assert!(
            out.lines()
                .all(|l| !l.starts_with(['-', '#']) && !l.starts_with("1."))
        );
        out.clear();
        push_wrapped(&mut out, &format!("{filler}*Differs here*"));
        assert!(out.lines().any(|l| l.starts_with("*Differs")));
    }

    #[test]
    fn the_embedded_data_makes_both_pages() {
        let pages = pages().expect("the data files are valid");
        assert!(pages[0].text.contains("function GetUnitExp("));
        assert!(pages[1].text.contains("function Round(value) end"));
    }
}
